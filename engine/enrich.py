ДЕЙСТВИЯ = [
    # ключ списка, действие, срок (ключ настроек), владелец (ключ), приоритет
    ("развивать",   "Дозаказать",  "срок_дозаказ_дней",     "владелец_дозаказ",     1),
    ("переместить", "Переместить", "срок_перемещение_дней", "владелец_перемещение", 2),
    ("медленные",   "Уценить",     "срок_уценка_дней",      "владелец_уценка",      3),
    ("вывести",     "Вывести",     "срок_вывод_дней",       "владелец_вывод",       4),
]


def собрать_задачи(списки: dict, cfg: dict, дата, лог) -> pd.DataFrame:
    """Плоский список задач: одна строка - одно действие по одной позиции."""
    пл = cfg.get("планирование", {})
    строки = []
    for ключ, действие, срок_к, влад_к, приор in ДЕЙСТВИЯ:
        df = списки.get(ключ)
        if df is None or not len(df):
            continue
        срок = pd.Timestamp(дата) + pd.Timedelta(days=int(пл.get(срок_к, 14)))
        for _, r in df.iterrows():
            if ключ == "переместить":
                сумма = float(r.get("Стоимость_перемещ") or 0)
                где = "%s -> %s" % (r.get("Офис_изб", ""), r.get("Офис_деф", ""))
                зачем = "лежит без спроса здесь, нужен там"
            elif ключ == "развивать":
                сумма = float(r.get("Упущено") or 0)
                где = ""
                зачем = "OOS %.0f%%, маржа %.0f%%" % (r.get("OOS_%") or 0, r.get("Маржа_%") or 0)
            else:
                сумма = float(r.get("Запас") or 0)
                где = ""
                возраст = r.get("Возраст")
                зачем = ("лежит %.0f дн, содержание %.0f руб/год"
                         % (возраст if pd.notna(возраст) else -1, r.get("Владение") or 0))
            строки.append({
                "Приоритет": приор, "Действие": действие,
                "НС-Код": r.get("НС-Код"), "Наименование": r.get("Название номенклатуры"),
                "Бренд": r.get("Бренд"), "Направление": r.get("Товарное направление"),
                "Склады": где, "Сумма, ₽": сумма, "Почему": зачем,
                "Решение юнит-экономики": r.get("ЮЭ_решение", ""),
                "Срок": срок.date().isoformat(),
                "Ответственный": пл.get(влад_к, ""), "Статус": "", "Комментарий": "",
            })
    if not строки:
        return pd.DataFrame()
    t = pd.DataFrame(строки).sort_values(["Приоритет", "Сумма, ₽"], ascending=[True, False])
    лог("   Задачи: %d строк на %.2f млн руб." % (len(t), t["Сумма, ₽"].sum() / 1e6))
    return t


