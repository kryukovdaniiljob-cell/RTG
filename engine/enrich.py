СНИМОК = "снимки.json"


def _снимок(S: dict, списки: dict) -> dict:
    сп = {}
    for k in ("вывести", "новинки", "медленные", "развивать"):
        df = списки.get(k)
        сп[k] = sorted(df["НС-Код"].astype(str).tolist()) if df is not None and len(df) else []
    return {
        "дата_данных": S["дата"],
        "посчитано": dt.datetime.now().isoformat(timespec="seconds"),
        "запас": S["запас"], "оборот": S["оборот"], "вп": S["вп"],
        "маржа": S["маржа"], "gmroi": S["gmroi"], "эконом_прибыль": S["эконом_прибыль"],
        "oos": S["oos"], "упущено": S["упущено"], "fill_rate": S["fill_rate"],
        "sku": S["sku"], "списки": сп,
    }


def сохранить_снимок(S: dict, списки: dict, корень: str, cfg: dict, лог) -> None:
    if not cfg.get("сравнение", {}).get("включено", True):
        return
    путь = os.path.join(корень, "база", СНИМОК)
    os.makedirs(os.path.dirname(путь), exist_ok=True)
    история = []
    if os.path.exists(путь):
        try:
            история = json.load(open(путь, encoding="utf-8"))
        except Exception:
            история = []
    нов = _снимок(S, списки)
    история = [x for x in история if x.get("дата_данных") != нов["дата_данных"]]
    история.append(нов)
    история = sorted(история, key=lambda x: x.get("посчитано", ""))[-60:]
    json.dump(история, open(путь, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    лог("   Снимок сохранён, всего в истории: %d" % len(история))


def сравнить_с_прошлым(S: dict, списки: dict, корень: str, cfg: dict, лог) -> dict:
    """Что изменилось с предыдущего расчёта."""
    if not cfg.get("сравнение", {}).get("включено", True):
        return {}
    путь = os.path.join(корень, "база", СНИМОК)
    if not os.path.exists(путь):
        лог("   Сравнивать не с чем — это первый расчёт")
        return {}
    try:
        история = json.load(open(путь, encoding="utf-8"))
    except Exception:
        return {}
    прошлые = [x for x in история if x.get("дата_данных") != S["дата"]]
    if not прошлые:
        лог("   Сравнивать не с чем — предыдущих расчётов по другим датам нет")
        return {}
    пред = прошлые[-1]
    порог = float(cfg.get("сравнение", {}).get("порог_значимости_руб", 50000))

    изм = {"с_датой": пред.get("дата_данных"), "порог": порог, "показатели": [], "списки": {}}
    ПОКАЗ = [("запас", "Запас, ₽", "руб", -1), ("оборот", "Оборот, ₽", "руб", 1),
             ("вп", "Валовая прибыль, ₽", "руб", 1), ("маржа", "Маржа, %", "пц", 1),
             ("gmroi", "GMROI", "коэф", 1), ("эконом_прибыль", "Эконом. прибыль, ₽/год", "руб", 1),
             ("oos", "OOS, %", "пц", -1), ("упущено", "Упущенные продажи, ₽", "руб", -1),
             ("fill_rate", "Fill Rate, %", "пц", 1)]
    for ключ, имя, тип, знак_хорошо in ПОКАЗ:
        прежнее = пред.get(ключ)
        if прежнее is None or ключ not in S:
            continue
        было, стало = float(прежнее), float(S[ключ])
        д = стало - было
        изм["показатели"].append({
            "имя": имя, "было": было, "стало": стало, "дельта": д, "тип": тип,
            "хорошо": (д * знак_хорошо) > 0, "значимо": abs(д) > (порог if тип == "руб" else 0.1),
        })
    for k in ("вывести", "новинки", "медленные", "развивать"):
        старое = set(пред.get("списки", {}).get(k, []))
        df = списки.get(k)
        новое = set(df["НС-Код"].astype(str)) if df is not None and len(df) else set()
        изм["списки"][k] = {"добавилось": len(новое - старое), "ушло": len(старое - новое),
                            "стало": len(новое), "было": len(старое),
                            "новые": sorted(новое - старое)[:20]}
    лог("   Сравнение с расчётом от %s: %d показателей" % (пред.get("дата_данных"), len(изм["показатели"])))
    return изм


