def приоритеты(S: dict, cfg: dict) -> list[dict]:
    """Матрица усилие-эффект: что делать первым."""
    P = []
    def доб(имя, деньги, эффект_год, усилие, срок, комментарий):
        P.append({"имя": имя, "деньги": деньги, "эффект_год": эффект_год,
                  "усилие": усилие, "срок": срок, "комментарий": комментарий,
                  "отдача": эффект_год / max(усилие, 1)})
    доб("Перемещение вместо закупки", S["переместить"]["сумма"],
        S["переместить"]["сумма"] * float(cfg["экономика"]["ставка_хранения"]),
        1, "2 недели", "не требует ничьего согласования, только логистика")
    доб("Дозаказ ходовых в дефиците", 0, S["упущено"],
        2, "1 месяц", "деньги нужны на закупку, но возврат самый быстрый")
    доб("Уценка медленного товара", S["медленные"]["запас"] / 2,
        S["медленные"]["владение"] / 2,
        3, "3 месяца", "нужно согласование скидки и работа менеджеров")
    доб("Вывод неликвида", S["вывести"]["запас"], S["вывести"]["владение"],
        4, "1 месяц", "часть можно вернуть поставщику, часть списать")
    return sorted(P, key=lambda x: -x["отдача"])


def цена_бездействия(S: dict, cfg: dict, кварталов: float = 1.0) -> dict:
    """Во что обойдётся ничего не делать."""
    ставка = float(cfg["экономика"]["ставка_хранения"]) + float(cfg["экономика"]["ставка_капитала"])
    мёртвый = S["вывести"]["запас"] + S["новинки"]["запас"] * 0.3
    содержание = мёртвый * ставка * кварталов / 4
    медленный = S["медленные"]["владение"] * кварталов / 4
    дефицит = S["упущено"] * кварталов / 3      # упущенное за период -> за квартал
    маржа_деф = дефицит * (S["маржа"] / 100)
    return {"кварталов": кварталов,
            "содержание_неликвида": содержание,
            "содержание_медленного": медленный,
            "упущенный_оборот": дефицит,
            "упущенная_прибыль": маржа_деф,
            "итого_потери": содержание + медленный + маржа_деф,
            "замороженный_капитал": S["вывести"]["запас"] + S["медленные"]["запас"] / 2}


