def лист_по_складам(W, wb, факт, S, cfg, форматы, созданные, лог=print):
    """Та же иерархия, но от склада: для разговора с каждым складом отдельно."""
    if факт is None or not len(факт):
        return
    import metrics as _m
    Fh, Ft, Fn, F2, Fp = форматы["h"], форматы["t"], форматы["n"], форматы["2"], форматы["p"]
    порог = S["порог"]; хор = float(cfg["экономика"]["порог_gmroi_хороший"])
    мин = float(cfg.get("отчёты", {}).get("минимум_склада_руб", 100000))

    f = факт.copy()
    активные = f.groupby("Склад")[["Оборот", "Запас"]].sum()
    активные = активные[(активные["Оборот"] + активные["Запас"]) >= мин].index
    f = f[f["Склад"].isin(активные)]
